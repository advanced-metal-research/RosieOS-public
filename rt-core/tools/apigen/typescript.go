package main

import (
	"fmt"
	"strings"
)

func tsType(t string) string {
	if strings.HasPrefix(t, "*") {
		return tsType(t[1:]) + " | null"
	}
	if strings.HasPrefix(t, "[") {
		return "Array<" + tsType(t[strings.Index(t, "]")+1:]) + ">"
	}
	if scalarMap(t) {
		return "Record<string, " + tsType(strings.TrimPrefix(t, "map[string]")) + ">"
	}
	switch t {
	case "string", "HandleState":
		return "string"
	case "bool":
		return "boolean"
	case "json", "rawjson":
		return "unknown"
	case "uint64", "int64", "int", "uint32", "int32", "uint16", "uint8", "float64":
		return "number"
	}
	return t
}

// generateTypeScript emits declarations without imports or runtime dependencies;
// binary counters use bigint so full-rate cursors cannot lose integer precision.
func generateTypeScript(s Schema, digest string) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by tools/apigen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Measured SHA256 of canonical application schema bytes.\nexport const CapabilitiesDigest = %q;\n", digest)
	fmt.Fprintf(&b, "// Unverified application contract identity.\nexport const ContractVersion = %d;\nexport const RequestSchema = %q;\nexport const ResponseSchema = %q;\n", s.ContractVersion, s.RequestSchema, s.ResponseSchema)
	for _, r := range s.Reasons {
		fmt.Fprintf(&b, "// %s Unverified outside the tested boundary.\nexport const Reason%s = %q;\n", r.Meaning, identifier(r.Name), r.Name)
	}
	for _, c := range s.Capabilities {
		fmt.Fprintf(&b, "// Unverified application capability.\nexport const Operation%s = %q;\n", identifier(c.Name), c.Name)
	}
	b.WriteString("// Unverified capability inventory; no authorization is implied.\nexport const Capabilities = [\n")
	for _, c := range s.Capabilities {
		fmt.Fprintf(&b, "  {name:%q,state:%q,transport:%q},\n", c.Name, c.State, c.Transport)
	}
	b.WriteString("] as const;\n")
	for _, t := range s.Types {
		fmt.Fprintf(&b, "export interface %s {\n", t.Name)
		for _, f := range t.Fields {
			if f.Embedded {
				continue
			}
			typ := tsType(f.Type)
			if t.Binary && f.Type == "uint64" {
				typ = "bigint"
			}
			if t.Binary && f.Type == "[]uint8" {
				typ = "Uint8Array"
			}
			optional := ""
			if !f.Required {
				optional = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", f.JSON, optional, typ)
		}
		b.WriteString("}\n")
	}
	// Embedded Go fields are flattened on the public wire.
	out := b.String()
	for _, t := range s.Types {
		var parents []string
		for _, f := range t.Fields {
			if f.Embedded {
				parent := f.Type
				if !f.Required {
					parent = "Partial<" + parent + ">"
				}
				parents = append(parents, parent)
			}
		}
		if len(parents) > 0 {
			out = strings.Replace(out, "interface "+t.Name+" {", "interface "+t.Name+" extends "+strings.Join(parents, ", ")+" {", 1)
		}
	}
	return []byte(out)
}
