package main

import (
	"fmt"
	"strings"
)

// generateTypeScript uses schema offsets and little-endian DataView reads;
// size/reserved checks reject partial frames before exposing decoded values.
func generateTypeScript(s protocolSchema) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by tools/protocolgen; DO NOT EDIT.\n")
	known := map[string]wireRecord{}
	for _, r := range s.wireRecords {
		known[r.Name] = r
	}
	if r, ok := known["CycleCaptureRecordV2"]; ok {
		fmt.Fprintf(&b, "// Measured SHA256 of generated transitive record layout.\nexport const CycleCaptureRecordV2LayoutDigest = %q;\n", recordDigest(r, known))
		b.WriteString(`// Refuse incompatible telemetry before a caller can decode its record body.
export class TelemetryLayoutMismatchError extends Error {
  readonly storedDigest: string;
  readonly expectedDigest: string;
  constructor(storedDigest: string, expectedDigest: string) {
    super("telemetry layout digest mismatch: stored=" + storedDigest + " expected=" + expectedDigest);
    this.name = "TelemetryLayoutMismatchError";
    this.storedDigest = storedDigest;
    this.expectedDigest = expectedDigest;
  }
}
`)
	}
	for _, name := range []string{"CycleCaptureAxisV2", "CycleCaptureRecordV2", "TelemetryBatchHeaderV1"} {
		r, ok := known[name]
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "// Measured generated wire size in bytes.\nexport const %sBytes = %d;\nexport interface %s {\n", name, r.Size, name)
		for _, f := range r.Fields {
			typ := "number"
			if f.base == "u64" || f.base == "i64" {
				typ = "bigint"
			}
			if _, ok := known[f.base]; ok {
				typ = f.base
			}
			if f.count > 0 {
				typ = "Array<" + typ + ">"
			}
			fmt.Fprintf(&b, "  %s: %s;\n", camel(f.Name), typ)
		}
		fmt.Fprintf(&b, "}\n// Decode a complete frame; malformed sizes and reserved values never escape.\nexport function decode%s(bytes: Uint8Array): %s {\n  if (bytes.byteLength !== %d) throw new Error(%q);\n  const v = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);\n", name, name, r.Size, "invalid "+name+" size")
		for _, f := range r.Fields {
			if f.Reserved {
				fmt.Fprintf(&b, "  for (let i=%d; i<%d; i++) if (v.getUint8(i)!==0) throw new Error(%q);\n", f.Offset, f.Offset+f.Size, "nonzero reserved field: "+f.Name)
			}
		}
		if name == "TelemetryBatchHeaderV1" {
			for _, f := range r.Fields {
				if f.Name == "record_layout_digest" {
					fmt.Fprintf(&b, "  const storedDigest = String.fromCharCode(...bytes.subarray(%d,%d));\n  if (storedDigest !== CycleCaptureRecordV2LayoutDigest) throw new TelemetryLayoutMismatchError(storedDigest,CycleCaptureRecordV2LayoutDigest);\n", f.Offset, f.Offset+f.Size)
				}
			}
		}
		b.WriteString("  return {\n")
		for _, f := range r.Fields {
			offset := fmt.Sprint(f.Offset)
			if f.count > 0 {
				offset = fmt.Sprintf("%d+i*%d", f.Offset, f.Size/f.count)
			}
			getter := map[string]string{"u8": "getUint8", "i8": "getInt8", "u16": "getUint16", "i16": "getInt16", "u32": "getUint32", "i32": "getInt32", "u64": "getBigUint64", "i64": "getBigInt64", "f64": "getFloat64"}[f.base]
			expr := ""
			if child, ok := known[f.base]; ok {
				expr = fmt.Sprintf("decode%s(bytes.subarray(%s,(%s)+%d))", f.base, offset, offset, child.Size)
			} else {
				endian := ",true"
				if scalarWidth[f.base] == 1 {
					endian = ""
				}
				expr = fmt.Sprintf("v.%s(%s%s)", getter, offset, endian)
			}
			if f.count > 0 {
				expr = fmt.Sprintf("Array.from({length:%d},(_,i)=>%s)", f.count, expr)
			}
			fmt.Fprintf(&b, "    %s: %s,\n", camel(f.Name), expr)
		}
		b.WriteString("  };\n}\n")
	}
	return []byte(b.String())
}
