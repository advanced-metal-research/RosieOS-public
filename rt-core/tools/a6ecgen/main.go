// Command a6ecgen preserves the manual's alarm/fault rows in a C++ table.
// It rejects malformed codes so a generated lookup cannot silently mislabel one.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strconv"
)

type codeRow struct {
	Code       string `json:"code"`
	Name       string `json:"name"`
	Bus        string `json:"bus_fault_code_603f"`
	Alarm      string `json:"alarm_code_203f"`
	Fault      string `json:"fault_code_203f"`
	Resettable bool   `json:"resettable"`
	Class      string `json:"class"`
}

func rows(body []byte) ([]codeRow, error) {
	var root map[string]json.RawMessage
	if err := json.Unmarshal(body, &root); err != nil {
		return nil, err
	}
	var result []codeRow
	var walk func(json.RawMessage) error
	walk = func(raw json.RawMessage) error {
		var object map[string]json.RawMessage
		if err := json.Unmarshal(raw, &object); err != nil {
			return nil
		}
		if _, ok := object["code"]; ok {
			var row codeRow
			if err := json.Unmarshal(raw, &row); err != nil {
				return err
			}
			if row.Alarm == "" {
				row.Alarm = row.Fault
			}
			if row.Name == "" || row.Code == "" || row.Alarm == "" {
				return fmt.Errorf("incomplete row: %s", row.Code)
			}
			for _, code := range []string{row.Bus, row.Alarm} {
				if code == "" {
					continue
				} // Null bus mapping remains explicitly unavailable.
				if _, err := strconv.ParseUint(code, 0, 16); err != nil {
					return err
				}
			}
			result = append(result, row)
			return nil
		}
		for _, child := range object {
			if err := walk(child); err != nil {
				return err
			}
		}
		return nil
	}
	if err := walk(root["tables"]); err != nil {
		return nil, err
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Code < result[j].Code })
	for i := 1; i < len(result); i++ {
		if result[i-1].Code == result[i].Code {
			return nil, fmt.Errorf("duplicate display code: %s", result[i].Code)
		}
	}
	if len(result) == 0 {
		return nil, fmt.Errorf("empty manual table")
	}
	return result, nil
}

func generate(body []byte) ([]byte, error) {
	entries, err := rows(body)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by tools/a6ecgen from docs/drives/a6ec/a6ec_manual_codes.json; DO NOT EDIT.\n#pragma once\n#include <cstdint>\n\nnamespace rosie::rtcore {\nstruct A6ECAlarmCode {\n  const char* display_code;\n  const char* meaning;\n  uint16_t bus_code, aux_code;\n  bool resettable;\n  const char* alarm_class;\n  bool bus_valid;\n};\n// Manual-derived values; resettable flags are unverified on hardware and never authorize reset.\ninline constexpr A6ECAlarmCode a6ec_alarm_codes[] = {\n")
	for _, row := range entries {
		bus, _ := strconv.ParseUint(row.Bus, 0, 16)
		aux, _ := strconv.ParseUint(row.Alarm, 0, 16)
		fmt.Fprintf(&out, "  {%s, %s, 0x%04x, 0x%04x, %t, %s, %t},\n", strconv.QuoteToASCII(row.Code), strconv.QuoteToASCII(row.Name), bus, aux, row.Resettable, strconv.QuoteToASCII(row.Class), row.Bus != "")
	}
	fmt.Fprint(&out, "};\n} // namespace rosie::rtcore\n")
	return out.Bytes(), nil
}

func main() {
	check := flag.Bool("check", false, "reject generated table drift without writing")
	flag.Parse()
	body, err := os.ReadFile("docs/drives/a6ec/a6ec_manual_codes.json")
	if err == nil {
		var output []byte
		output, err = generate(body)
		if err == nil {
			path := "include/a6ec_alarm_codes_generated.hpp"
			if *check {
				var current []byte
				current, err = os.ReadFile(path)
				if err == nil && !bytes.Equal(current, output) {
					err = fmt.Errorf("generated alarm table drift: %s", path)
				}
			} else {
				err = os.WriteFile(path, output, 0644)
			}
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
