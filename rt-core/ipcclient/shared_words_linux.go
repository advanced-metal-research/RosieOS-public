//go:build linux

package ipcclient

import (
	"encoding/binary"
	"runtime"
	"sync/atomic"
	"unsafe"
)

type sharedWordsStatus uint8

const (
	sharedWordsOK sharedWordsStatus = iota
	sharedWordsUnbound
	sharedWordsInvalidGeometry
	sharedWordsMisaligned
	sharedWordsInvalidBuffer
	sharedWordsUnpublished
	sharedWordsBusy
	sharedWordsSequenceExhausted
	sharedWordsUnsupportedPlatform
)

const sharedWordsReadAttempts = 2

// sharedWords borrows one aligned sequence word followed by a fixed number of
// payload words. One publisher owns the slot. The mapping owner must initialize
// new storage before sharing it and quiesce all users before unmapping it.
// An odd/exhausted sequence is never reset in place: use a fresh incarnation.
type sharedWords struct {
	data  []byte
	count int
}

func bindSharedWords(mapping []byte, payloadWords int) (sharedWords, sharedWordsStatus) {
	if runtime.GOARCH != "amd64" && runtime.GOARCH != "arm64" {
		return sharedWords{}, sharedWordsUnsupportedPlatform
	}
	if payloadWords < 1 || len(mapping)%8 != 0 || payloadWords >= len(mapping)/8 || len(mapping)/8-1 != payloadWords {
		return sharedWords{}, sharedWordsInvalidGeometry
	}
	if uintptr(unsafe.Pointer(&mapping[0]))%8 != 0 {
		return sharedWords{}, sharedWordsMisaligned
	}
	return sharedWords{mapping, payloadWords}, sharedWordsOK
}

func sharedWordsOverlap(first unsafe.Pointer, firstBytes uintptr, second unsafe.Pointer, secondBytes uintptr) bool {
	if firstBytes == 0 || secondBytes == 0 {
		return false
	}
	a, b := uintptr(first), uintptr(second)
	if a <= b {
		return b-a < firstBytes
	}
	return a-b < secondBytes
}

func (s sharedWords) localBuffer(words []uint64) bool {
	return len(words) == s.count && !sharedWordsOverlap(unsafe.Pointer(&words[0]), uintptr(len(words))*8,
		unsafe.Pointer(&s.data[0]), uintptr(len(s.data)))
}

func (s sharedWords) word(index int) *uint64 {
	return (*uint64)(unsafe.Pointer(&s.data[index*8]))
}

// publish never waits for a reader. CAS detects an interrupted or overlapping
// publisher; the caller must still enforce one writer. All concurrent sequence
// and payload accesses use Go's sequentially consistent 64-bit atomic operations.
func (s sharedWords) publish(input []uint64) (uint64, sharedWordsStatus) {
	if s.data == nil {
		return 0, sharedWordsUnbound
	}
	if !s.localBuffer(input) {
		return 0, sharedWordsInvalidBuffer
	}
	sequence := atomic.LoadUint64(s.word(0))
	if sequence&1 != 0 {
		return 0, sharedWordsBusy
	}
	if sequence > ^uint64(0)-2 {
		return 0, sharedWordsSequenceExhausted
	}
	if !atomic.CompareAndSwapUint64(s.word(0), sequence, sequence+1) {
		return 0, sharedWordsBusy
	}
	for word, value := range input {
		atomic.StoreUint64(s.word(word+1), value)
	}
	atomic.StoreUint64(s.word(0), sequence+2)
	return sequence + 2, sharedWordsOK
}

// read requires independent caller-owned output and scratch buffers. It makes
// at most two attempts and changes output only on success. Input expiry and any
// previously accepted value belong to the caller, never this storage primitive.
func (s sharedWords) read(output, scratch []uint64) (uint64, sharedWordsStatus) {
	if s.data == nil {
		return 0, sharedWordsUnbound
	}
	if !s.localBuffer(output) || !s.localBuffer(scratch) ||
		sharedWordsOverlap(unsafe.Pointer(&output[0]), uintptr(len(output))*8, unsafe.Pointer(&scratch[0]), uintptr(len(scratch))*8) {
		return 0, sharedWordsInvalidBuffer
	}
	for attempt := 0; attempt < sharedWordsReadAttempts; attempt++ {
		sequence := atomic.LoadUint64(s.word(0))
		if sequence == 0 {
			return 0, sharedWordsUnpublished
		}
		if sequence&1 != 0 {
			continue
		}
		for word := range scratch {
			scratch[word] = atomic.LoadUint64(s.word(word + 1))
		}
		if sequence == atomic.LoadUint64(s.word(0)) {
			copy(output, scratch)
			return sequence, sharedWordsOK
		}
	}
	return 0, sharedWordsBusy
}

// Codec bridges operate only on independent local buffers: encode bytes,
// convert to words, publish; or read words, convert to bytes, decode. Reject
// overlap before changing the destination. Never use a generated byte codec
// directly on a live shared payload.
func sharedWordsFromLE(output []uint64, encoded []byte) sharedWordsStatus {
	if len(output) == 0 || len(encoded)%8 != 0 || len(encoded)/8 != len(output) {
		return sharedWordsInvalidGeometry
	}
	if sharedWordsOverlap(unsafe.Pointer(&output[0]), uintptr(len(output))*8,
		unsafe.Pointer(&encoded[0]), uintptr(len(encoded))) {
		return sharedWordsInvalidBuffer
	}
	for word := range output {
		output[word] = binary.LittleEndian.Uint64(encoded[word*8:])
	}
	return sharedWordsOK
}

func sharedWordsToLE(encoded []byte, input []uint64) sharedWordsStatus {
	if len(input) == 0 || len(encoded)%8 != 0 || len(encoded)/8 != len(input) {
		return sharedWordsInvalidGeometry
	}
	if sharedWordsOverlap(unsafe.Pointer(&encoded[0]), uintptr(len(encoded)),
		unsafe.Pointer(&input[0]), uintptr(len(input))*8) {
		return sharedWordsInvalidBuffer
	}
	for word, value := range input {
		binary.LittleEndian.PutUint64(encoded[word*8:], value)
	}
	return sharedWordsOK
}
